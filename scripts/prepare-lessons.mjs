import fs from 'node:fs';
import crypto from 'node:crypto';
import { parseHTML } from 'linkedom';

const root = new URL('../', import.meta.url);
const read = (path) => fs.readFileSync(new URL(path, root), 'utf8');
const write = (path, text) => fs.writeFileSync(new URL(path, root), text);
const quests = JSON.parse(read('design/quests.json'));
const screenshots = JSON.parse(read('research/screenshot-text-refined.json'));
const manualCorrections = JSON.parse(read('research/ocr-manual-corrections.json'));
fs.mkdirSync(new URL('public/assets/instructions/', root), { recursive: true });
const esc = (s) => s.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');

// Rebuild instructional images with new vector surfaces and searchable text.
// Text positions and wording come from local OCR, never generated by an image model.
for (const shot of screenshots) {
  for(const line of shot.lines)line.text=manualCorrections[shot.id]?.[line.text]||line.text;
  const w = shot.width, h = shot.height;
  const title = [...new Set(shot.labels.filter(Boolean))][0] || '실습 화면';
  const rows = shot.lines.filter(line=>!/(?:KIST|KST).*(?:인턴|작성|전략|간학|간박)|문의.*(?:인턴|오고)|rhdms|오고은|오고온/i.test(line.text)).map((line) => {
    const size = Math.max(8, line.h * h * 1.03);
    const y = line.y * h + line.h * h * .85 + 38;
    const x = line.x * w;
    return `<text x="${x.toFixed(1)}" y="${y.toFixed(1)}" font-size="${size.toFixed(1)}" textLength="${Math.max(2, line.w * w).toFixed(1)}" lengthAdjust="spacingAndGlyphs">${esc(line.text)}</text>`;
  }).join('\n');
  const folder=w<240&&h<200&&/폴더/.test(title)?`<g transform="translate(${w*.27},${38+h*.1}) scale(${w*.46/48})"><path d="M2 8h17l5 6h22v28H2Z" fill="#ddbd82" stroke="#ad8050"/><path d="M2 16h44v26H2Z" fill="#e8cea0" stroke="#ad8050"/><path d="M7 22h33" stroke="#f9efd9"/></g>`:'';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h + 38}" viewBox="0 0 ${w} ${h + 38}" role="img"><title>${esc(title)}</title><rect width="100%" height="100%" rx="6" fill="#fffdf8"/><path d="M0 38H${w}" stroke="#d8cfc0"/><circle cx="13" cy="19" r="3" fill="#ae583f"/><circle cx="24" cy="19" r="3" fill="#b7a079"/><circle cx="35" cy="19" r="3" fill="#87937b"/>${w>300?`<text x="${w-12}" y="23" text-anchor="end" font-family="sans-serif" font-size="10" fill="#7d7569">FIELD NOTES · ${esc(title.slice(0, 38))}</text>`:''}${folder}<g fill="#293d36" font-family="'Noto Sans KR','Apple SD Gothic Neo',sans-serif">${rows}</g><rect x=".5" y=".5" width="${w-1}" height="${h+37}" rx="6" fill="none" stroke="#d8cfc0"/></svg>`;
  write(`public/assets/instructions/${shot.id}.svg`, svg);
}

const colors = new Map(Object.entries({
  '#080F0C':'#f4eee3','#111C16':'#fffdf8','#1A2A21':'#eae4d7','#0E1813':'#fffdf8',
  '#D2DCCB':'#293d36','#8A9B8C':'#686b5d','#5D6D61':'#7b796b',
  '#F2E1A4':'#ad553a','#E2914E':'#a64f33','#6FC0A1':'#496550',
  '#9ED8F5':'#3c727a','#8EEFC0':'#4e7254','#D4685E':'#b44938',
  '#0C1512':'#f8f3e9','#050A08':'#ede5d7','#10201A':'#f4eee3',
  '#0B1410':'#fffdf8','#060D0A':'#f4eee3','#E6F6FF':'#253c36','#E9FFF3':'#253c36',
  '#E4CDF6':'#754a3c','#E7B3AC':'#a94b3c','#F7EFD6':'#293d36','#cfe3d8':'#496550'
}));
const rgb = {'210,220,203':'41,61,54','17,28,22':'255,253,248','8,15,12':'244,238,227','26,42,33':'234,228,215','242,225,164':'173,85,58','111,192,161':'73,101,80','140,240,190':'78,114,84','120,195,255':'102,137,139','190,230,255':'181,202,190','140,200,255':'92,132,134','120,190,255':'92,132,134'};
function recolor(css) {
  for (const [a,b] of colors) css = css.replace(new RegExp(a, 'gi'), b);
  css = css.replace(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)/g, (all,r,g,b) => all.replace(/\d+\s*,\s*\d+\s*,\s*\d+/, rgb[`${r},${g},${b}`] || `${r},${g},${b}`));
  return css.replaceAll('"Gowun Batang"','"Noto Serif KR"').replaceAll('"Cinzel"','"DM Mono"').replaceAll('"IBM Plex Mono"','"DM Mono"').replace(/(font-size\s*:\s*)([\d.]+)cqw/g, '$1max(12px,$2cqw)');
}

const baseline = [];
for (const q of quests.quests) {
  const week = q.week;
  let raw = read(`research/week-${week}-authored.html`);
  // Replace every authored story raster, including all hero poses, with new art.
  raw = raw.replace(/(--[\w-]+)\s*:\s*url\(["']?data:image\/[^;]+;base64,[A-Za-z0-9+/=]+["']?\)/g, (all, key) => {
    const asset = key === '--cabin' ? (week <= 2 ? 'cabin' : week <= 5 ? 'cave' : 'grove') : key === '--fairy' ? 'fairy' : key === '--boss' ? 'boss' : key === '--dr' ? 'doctor' : 'hero';
    return `${key}:url("../assets/${asset}.webp")`;
  });
  const { document } = parseHTML(raw);
  for (const credit of document.querySelectorAll('.byline,.endsign')) credit.remove();
  for (const im of document.querySelectorAll('img[src^="data:image/"]')) {
    const hash = crypto.createHash('sha256').update(im.getAttribute('src')).digest('hex').slice(0,16);
    const shot = screenshots.find(s => s.id === hash);
    if (!shot) throw new Error(`Missing screenshot ${hash}`);
    im.setAttribute('src', `../assets/instructions/${hash}.svg`);
    if (!im.getAttribute('alt')) im.setAttribute('alt', [...new Set(shot.labels.filter(Boolean))][0] || '실습 절차 화면 — 클릭하여 확대');
    im.setAttribute('loading','lazy');
    im.classList.remove('small');
  }
  for (const style of document.querySelectorAll('style')) style.textContent = recolor(style.textContent).replace(/url\(["']?data:image\/[^;]+;base64,[A-Za-z0-9+/=]+["']?\)/g, 'url("../assets/boss.webp")');
  for (const font of document.querySelectorAll('link[href*="fonts.googleapis.com/css"]')) font.setAttribute('href','https://fonts.googleapis.com/css2?family=Noto+Serif+KR:wght@400;600;700&family=Noto+Sans+KR:wght@400;500;600;700&family=DM+Mono:wght@400;500&display=swap');
  for (const script of document.querySelectorAll('script')) {
    script.textContent = script.textContent.replace(/var CK = 'oin-([^']+)'/, "var CK = 'journey-$1'");
    // Provide the new reader shell a narrow interface; the original exercise logic stays intact.
    if (script.textContent.includes('function show(n)')) {
      script.textContent = script.textContent.replace(/(var slides = [^;]+;)/, '$1\n  window.Journey = { go: show, step: step, sync: typeof syncHp === "function" ? syncHp : function(){} };');
      if (!script.textContent.includes('window.Journey')) throw new Error(`No boot marker week ${week}`);
    }
  }
  const titles = [...document.querySelectorAll('section.slide')].map((s,index) => ({ index, id:s.id, title:s.getAttribute('data-name'), hidden:s.hasAttribute('data-hidden') }));
  const text = [...document.querySelectorAll('section.slide')].map(s => s.textContent.replace(/\s+/g,' ').trim());
  baseline.push({week, count:titles.length, titles, hashes:text.map(t=>crypto.createHash('sha256').update(t).digest('hex'))});
  for (const a of document.querySelectorAll('a[href="https://claude.ai/artifact/VvATMCBaL7kZjrnw3rQ7cj"]')) { a.setAttribute('href','../'); a.removeAttribute('target'); }
  document.documentElement.setAttribute('lang','ko');
  document.body.setAttribute('data-week',String(week));
  const storageKey = [...document.querySelectorAll('script')].map(s=>s.textContent.match(/var CK = '([^']+)'/)).find(Boolean)?.[1];
  if(storageKey)document.body.setAttribute('data-check-storage',storageKey);
  const title = document.querySelector('title') || document.createElement('title');
  title.textContent = `WEEK ${String(week).padStart(2,'0')} · ${q.title}`;
  document.head.appendChild(title);
  const css=document.createElement('link');css.rel='stylesheet';css.href='./reader.css';document.body.appendChild(css);
  const bar=document.createElement('header');bar.className='lesson-bar';
  bar.innerHTML=`<a class="reader-home" href="../" aria-label="전체 지도">↖ <span>전체 지도</span></a><span class="reader-brand">CLAUDE / FIELD NOTES</span><button type="button" id="toc-open" aria-expanded="false" aria-controls="lesson-toc">목차 <span>☰</span></button>`;
  document.body.insertBefore(bar,document.body.firstChild);
  const meta=document.createElement('div');meta.className='reader-meta';meta.setAttribute('data-chapter',String(week).padStart(2,'0'));meta.innerHTML=`<span class="reader-week">CHAPTER</span><h1>${esc(q.title)}</h1><span>${esc(q.location)}</span>`;
  bar.insertAdjacentElement('afterend',meta);
  const aside=document.createElement('aside');aside.id='lesson-toc';aside.hidden=true;aside.setAttribute('aria-label','주차 목차');
  aside.innerHTML=`<div class="toc-head"><span>이번 여정의 기록</span><button id="toc-close" aria-label="목차 닫기">×</button></div><p>WEEK ${String(week).padStart(2,'0')} · ${titles.filter(t=>!t.hidden).length}개 장면</p><ol>${titles.filter(t=>!t.hidden).map(t=>`<li><button data-scene="${t.index}">${esc(t.title)}</button></li>`).join('')}</ol>`;
  document.body.appendChild(aside);
  const tail=document.createElement('div');tail.className='reader-tail';tail.innerHTML=`<span>← → 키로 이동 · 실습 화면은 클릭하여 확대</span>${week<8?`<a href="./week-${week+1}.html">다음 주차 살펴보기 ↗</a>`:'<a href="../">전체 지도 돌아가기 ↗</a>'}`;document.body.appendChild(tail);
  const js=document.createElement('script');js.src='./reader.js';document.body.appendChild(js);
  const result='<!doctype html>\n'+document.documentElement.outerHTML;
  if (/data:image\/[a-z]+;base64/.test(result)) throw new Error(`Original raster remains week ${week}`);
  if (/KIST|rhdms21109|오고은/.test(result)) throw new Error(`Credit remains week ${week}`);
  write(`public/lessons/week-${week}.html`, result);
}
write('research/content-baseline.json',JSON.stringify(baseline,null,2));
write('public/lessons/manifest.json',JSON.stringify(baseline.map(({hashes,...rest})=>rest),null,2));
console.log(`Prepared ${baseline.length} lessons, ${baseline.reduce((s,w)=>s+w.count,0)} scenes and ${screenshots.length} rebuilt illustrations.`);
